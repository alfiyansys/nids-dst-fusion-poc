"""Loaders for the real Snort/Suricata NDJSON sample logs under ``data/``.

The sample logs were generated by ``generate-synthetic-data.sh`` from the
Hyper-Parser repository's ``test-data/fusible`` fixture set (see
``data/fusible-sample/README.md`` for full provenance). They are genuine
engine output format, just synthetic in content, used here to demonstrate
the correlator against real Snort/Suricata JSON shapes rather than only
against the large calibrated simulation in :mod:`dst_fusion.simulate`.

Timestamps are converted to seconds relative to the earliest event across
both logs, so the two streams are directly comparable and feed straight into
:class:`dst_fusion.correlation.Correlator`.
"""
from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

from .correlation import Alert


def _read_ndjson(path: Path) -> list[dict]:
    records = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                records.append(json.loads(line))
    return records


def load_snort_alerts(path: str | Path) -> list[Alert]:
    """Parse a Snort JSON-alert NDJSON log into :class:`Alert` objects.

    Uses the human-readable ``timestamp`` field (``DD/MM/YY-HH:MM:SS.ffffff``),
    not the record's own ``seconds`` field: in this fixture set ``seconds``
    is consistently one year behind ``timestamp`` (an artifact of how
    ``generate-synthetic-data.sh`` computed it), which would push every
    Snort record outside any Suricata record's correlation window. The
    string field is the one that is actually consistent with the Suricata
    log's ISO timestamps.
    """
    alerts = []
    for rec in _read_ndjson(Path(path)):
        ts = datetime.strptime(rec["timestamp"], "%d/%m/%y-%H:%M:%S.%f").replace(
            tzinfo=timezone.utc
        ).timestamp()
        alerts.append(
            Alert(
                ts=ts,
                sensor_id="snort",
                priority=int(rec["priority"]),
                src_ip=rec.get("src_addr", ""),
                dst_ip=rec.get("dst_addr", ""),
                src_port=int(rec.get("src_port", 0)),
                dst_port=int(rec.get("dst_port", 0)),
                proto=rec.get("proto", ""),
                signature=rec.get("msg"),
            )
        )
    return alerts


def load_suricata_alerts(path: str | Path) -> list[Alert]:
    """Parse a Suricata EVE JSON NDJSON log into :class:`Alert` objects.

    Only ``event_type == "alert"`` records carry DST-relevant evidence;
    protocol-detection records (e.g. ``event_type: "ssh"``) are metadata the
    real Fusion Engine never receives and are skipped here for the same
    reason. Suricata's ``alert.severity`` is used directly as the unified
    priority value, mirroring how the adaptive-parser stage normalizes both
    engines onto the same priority-scaled field before either reaches the
    Fusion Engine (see the paper's Method / System Architecture).
    """
    alerts = []
    for rec in _read_ndjson(Path(path)):
        if rec.get("event_type") != "alert":
            continue
        ts = datetime.fromisoformat(rec["timestamp"]).astimezone(timezone.utc).timestamp()
        alert = rec["alert"]
        alerts.append(
            Alert(
                ts=ts,
                sensor_id="suricata",
                priority=int(alert["severity"]),
                src_ip=rec.get("src_ip", ""),
                dst_ip=rec.get("dest_ip", ""),
                src_port=int(rec.get("src_port", 0)),
                dst_port=int(rec.get("dest_port", 0)),
                proto=rec.get("proto", ""),
                signature=alert.get("signature"),
            )
        )
    return alerts


def load_fusible_sample(data_dir: str | Path) -> list[Alert]:
    """Load and merge the sample Snort + Suricata logs from ``data_dir``.

    Returns a single time-ordered list ready for
    ``Correlator.process_stream``.
    """
    data_dir = Path(data_dir)
    snort_path = next(data_dir.glob("snort_synthetic_*.json"))
    suricata_path = next(data_dir.glob("suricata_synthetic_*.json"))
    alerts = load_snort_alerts(snort_path) + load_suricata_alerts(suricata_path)
    return sorted(alerts, key=lambda a: a.ts)
